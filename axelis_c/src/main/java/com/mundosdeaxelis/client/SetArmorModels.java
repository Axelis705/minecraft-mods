    /** Modelo de armadura del set para la ranura (el pantalón usa el interior, el resto el exterior). */
    public static HumanoidModel<?> get(GearSet set, EquipmentSlot slot, HumanoidModel<?> fallback) {
        boolean inner = slot == EquipmentSlot.LEGS;
        String[] rows = (inner ? INNER : OUTER).get(set.id);
        if (rows == null) {
            return fallback;
        }
        String key = set.id + (inner ? "_i" : "_o");
        HumanoidModel<LivingEntity> m = CACHE.get(key);
        if (m == null) {
            m = new HumanoidModel<>(build(rows, inner).bakeRoot());
            CACHE.put(key, m);
        }
        return m;
    }

    /**
     * Cuánto sobresale por la espalda (en bloques) la armadura del set respecto al cuerpo, para que la capa no la atraviese ni
     * quede lejos. {@code upper}: la mitad de arriba del torso (cuello, hombros); si no, la de abajo (cinturón, faldón).
     */
    public static float backExtent(GearSet set, boolean innerLayer, boolean upper) {
        String[] rows = (innerLayer ? INNER : OUTER).get(set.id);
        float ext = innerLayer ? BASE_INNER : BASE_TORSO;
        if (rows != null) {
            float pull = innerLayer ? PULL : PULL_T;
            for (String r : rows) {
                String[] f = r.split(";");
                if (!f[0].equals("body")) {
                    continue;
                }
                float y = Float.parseFloat(f[4]);
                if ((y < 6.0F) != upper) {
                    continue;
                }
                float zb = (Float.parseFloat(f[5]) + Float.parseFloat(f[8]) + Float.parseFloat(f[9])) * pull - 2.0F;
                ext = Math.max(ext, zb);
            }
        }
        return Math.max(0.0F, ext) / 16.0F;
    }

    /** Cuánto más ceñida va la armadura base (antes 1,0 fuera y 0,5 dentro) y cuánto se achican y acercan los adornos. */
    private static final float BASE_OUTER = 0.88F, BASE_INNER = 0.42F, SHRINK = 0.86F, PULL = 0.92F;
    /** Torso y brazos (peto): más pegados al cuerpo que la cabeza y las piernas (antes 0,88 / 0,86 / 0,92). */
    private static final float BASE_TORSO = 0.70F, SHRINK_T = 0.74F, PULL_T = 0.78F, PULL_ARM_X = 0.55F;
    /** Botas (capa exterior de las piernas): más delgadas para que no formen un bloque grueso bajo el pantalón (antes 0,88 / 0,86 / 0,92). */
    private static final float BASE_BOOT = 0.60F, SHRINK_B = 0.78F, PULL_B = 0.88F;

    /** Centro de la caja base de cada parte (en las coordenadas de las filas). */
    private static float[] center(String part) {
        return switch (part) {
            case "head" -> new float[]{0F, -4F, 0F};
            case "right_arm" -> new float[]{-1F, 4F, 0F};
            case "left_arm" -> new float[]{1F, 4F, 0F};
            default -> new float[]{0F, 6F, 0F};
        };
    }

    private static LayerDefinition build(String[] rows, boolean inner) {
        CubeDeformation def = new CubeDeformation(inner ? BASE_INNER : BASE_OUTER);
        CubeDeformation defT = new CubeDeformation(inner ? BASE_INNER : BASE_TORSO);
        CubeDeformation defB = new CubeDeformation(inner ? BASE_INNER : BASE_BOOT);
        int dv = inner ? 32 : 0;
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        Map<String, PartDefinition> parts = new HashMap<>();
        parts.put("head", root.addOrReplaceChild("head", CubeListBuilder.create().texOffs(0, dv).addBox(-4.0F, -8.0F, -4.0F, 8.0F, 8.0F, 8.0F, def), PartPose.ZERO));
        root.addOrReplaceChild("hat", CubeListBuilder.create(), PartPose.ZERO);
        parts.put("body", root.addOrReplaceChild("body", CubeListBuilder.create().texOffs(16, 16 + dv).addBox(-4.0F, 0.0F, -2.0F, 8.0F, 12.0F, 4.0F, defT), PartPose.ZERO));
        parts.put("right_arm", root.addOrReplaceChild("right_arm", CubeListBuilder.create().texOffs(40, 16 + dv).addBox(-3.0F, -2.0F, -2.0F, 4.0F, 12.0F, 4.0F, defT), PartPose.offset(-5.0F, 2.0F, 0.0F)));
        parts.put("left_arm", root.addOrReplaceChild("left_arm", CubeListBuilder.create().texOffs(40, 16 + dv).mirror().addBox(-1.0F, -2.0F, -2.0F, 4.0F, 12.0F, 4.0F, defT), PartPose.offset(5.0F, 2.0F, 0.0F)));
        parts.put("right_leg", root.addOrReplaceChild("right_leg", CubeListBuilder.create().texOffs(0, 16 + dv).addBox(-2.0F, 0.0F, -2.0F, 4.0F, 12.0F, 4.0F, defB), PartPose.offset(-1.9F, 12.0F, 0.0F)));
        parts.put("left_leg", root.addOrReplaceChild("left_leg", CubeListBuilder.create().texOffs(0, 16 + dv).mirror().addBox(-2.0F, 0.0F, -2.0F, 4.0F, 12.0F, 4.0F, defB), PartPose.offset(1.9F, 12.0F, 0.0F)));
        for (int i = 0; i < rows.length; i++) {
            String[] f = rows[i].split(";");
            PartDefinition parent = parts.get(f[0]);
            int u = Integer.parseInt(f[1]);
            int v = Integer.parseInt(f[2]);
            float x = Float.parseFloat(f[3]);
            float y = Float.parseFloat(f[4]);
            float z = Float.parseFloat(f[5]);
            float w = Float.parseFloat(f[6]);
            float h = Float.parseFloat(f[7]);
            float d = Float.parseFloat(f[8]);
            float dg = Float.parseFloat(f[9]);
            float px = Float.parseFloat(f[10]);
            float py = Float.parseFloat(f[11]);
            float pz = Float.parseFloat(f[12]);
            float rx = (float) Math.toRadians(Float.parseFloat(f[13]));
            float ry = (float) Math.toRadians(Float.parseFloat(f[14]));
            float rz = (float) Math.toRadians(Float.parseFloat(f[15]));
            // Más pequeño y sin caras pegadas: cada cubo se encoge hacia su propio centro (la deformación negativa achica
            // la forma pero NO cambia el mapa de la textura) y se acerca un poco al centro de la parte; además cada uno
            // se infla un pelín distinto (0,01 por índice) para que dos caras en el mismo plano nunca "peleen" (z-fighting).
            float[] pc = center(f[0]);
            boolean torso = !inner && (f[0].equals("body") || f[0].equals("right_arm") || f[0].equals("left_arm"));
            boolean arm = f[0].equals("right_arm") || f[0].equals("left_arm");
            boolean boot = !inner && (f[0].equals("right_leg") || f[0].equals("left_leg"));
            float pull = torso ? PULL_T : boot ? PULL_B : PULL;
            float pullX = torso && arm ? PULL_ARM_X : pull;
            float shrink = torso ? SHRINK_T : boot ? SHRINK_B : SHRINK;
            float cx = pc[0] + (x + w / 2 - pc[0]) * pullX;
            float cy = pc[1] + (y + h / 2 - pc[1]) * pull;
            float cz = pc[2] + (z + d / 2 - pc[2]) * pull;
            float npx = pc[0] + (px - pc[0]) * pullX;
            float npy = pc[1] + (py - pc[1]) * pull;
            float npz = pc[2] + (pz - pc[2]) * pull;
            float jit = 0.01F * ((i % 6) + 1);
            float gx = dg + jit - w * (1.0F - shrink) / 2.0F;
            float gy = dg + jit - h * (1.0F - shrink) / 2.0F;
            float gz = dg + jit - d * (1.0F - shrink) / 2.0F;
            parent.addOrReplaceChild("extra" + i, CubeListBuilder.create().texOffs(u, v)
                            .addBox(cx - w / 2 - npx, cy - h / 2 - npy, cz - d / 2 - npz, w, h, d, new CubeDeformation(gx, gy, gz)),
                    PartPose.offsetAndRotation(npx, npy, npz, rx, ry, rz));
        }
        return LayerDefinition.create(mesh, 128, 128);
    }

def iconos():
    im = Image.new("RGBA", (128, 16), (0, 0, 0, 0))
    for idx, (dib, pal) in ICONOS.items():
        filas = [f for f in dib.strip("\n").split("\n")]
        for y, fila in enumerate(filas[:16]):
            for x, ch in enumerate(fila[:16]):
                if ch in pal:
                    im.putpixel((idx * 16 + x, y), pal[ch] + (255,))
    p = os.path.join(A, "textures", "gui", "estados.png")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    im.save(p)


def cristal():
    """Cristal largo y brillante (apunta hacia adelante, -z) para el proyectil del Coloso."""
    cry, cry2, oscuro = (150, 235, 255), (200, 120, 255), (90, 60, 160)

    def pintar(face, x, y, w, h):
        t = (x + y) / max(1, w + h)
        base = tuple(int(cry[i] + (cry2[i] - cry[i]) * t) for i in range(3))
        if x == 0 or y == 0:
            base = tuple(int(base[i] * 0.75 + oscuro[i] * 0.25) for i in range(3))
        return base + (255,)

    c = geo.Creature("geometry.axelis_core.cristal", 64, 32, seed=7)
    c.bone("root", [0, 0, 0])
    c.bone("cristal", [0, 0, 0], "root")
    c.part("cristal", [-1.5, -1.5, -5], [3, 3, 10], pintar, rotation=[0, 0, 45], pivot=[0, 0, 0])
    c.part("cristal", [-1, -1, -8], [2, 2, 3], pintar, rotation=[0, 0, 45], pivot=[0, 0, 0])
    c.part("cristal", [1, -0.5, -2], [1.5, 1.5, 5], pintar, rotation=[0, 18, 45], pivot=[1, 0, 0])
    c.part("cristal", [-2.5, -0.5, -1], [1.5, 1.5, 4], pintar, rotation=[0, -20, 45], pivot=[-1, 0, 0])
    c.glow("cristal")
    c.build(os.path.join(A, "geo", "cristal.geo.json"), os.path.join(A, "textures", "entity", "cristal.png"))



def orbe():
    """Círculo suave: blanco al centro que se apaga hacia afuera (sirve para brillos que se suman)."""
    n = 32
    im = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    c = (n - 1) / 2
    for y in range(n):
        for x in range(n):
            d = math.hypot(x - c, y - c) / (n / 2)
            k = max(0.0, 1 - d) ** 1.7
            if k > 0:
                v = int(255 * k)
                im.putpixel((x, y), (v, v, v, v))
    im.save(os.path.join(A, "textures", "fx", "orbe.png"))



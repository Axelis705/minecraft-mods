def variant(base, **over):
    out = {k: (dict(v) if isinstance(v, dict) else list(v) if isinstance(v, list) else v) for k, v in base.items()}
    for k, v in over.items():
        if k == "k":
            out["k"].update(v)
        else:
            out[k] = v
    return out


